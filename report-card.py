# This is a simple one person report card

student_name = 'Stephen' # student's name
print(student_name, type(student_name)) # output: student_name, data type

is_student = True # is this person a student: True
print(is_student, type(is_student)) # output: is_student, data type

student_age = 30 # student's age
print(student_age, type(student_age)) # output: student_age, data type

student_score = 85.5 # student's score
print(isinstance(student_score, float)) # output: student_score, checking to see if correct variable is allocated
print(student_score, type(student_score)) # output: student_score, data type
